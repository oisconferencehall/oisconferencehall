export const formatPrice = (price) => {
  if (price == null) return "0";
  return price.toString().replace(/\B(?=(\d{3})+(?!\d))/g, " ");
};

export const formatHallTitle = (hall, lang) => {
  if (!hall) return '';
  if (lang === 'ru' && (hall.titleRu || hall.title_ru)) return hall.titleRu || hall.title_ru;
  if (lang === 'uz' && (hall.titleUz || hall.title_uz)) return hall.titleUz || hall.title_uz;
  return hall.title;
};

export const formatHallDesc = (hall, lang) => {
  if (!hall) return '';
  if (lang === 'ru' && (hall.descriptionRu || hall.description_ru)) return hall.descriptionRu || hall.description_ru;
  if (lang === 'uz' && (hall.descriptionUz || hall.description_uz)) return hall.descriptionUz || hall.description_uz;
  return hall.description;
};

export const formatHallCapacity = (capacity, lang) => {
  if (!capacity) return '';
  const str = String(capacity);
  if (lang === 'ru') {
    return str.replace(/\bseats\b|\bpeople\b|\bcapacity\b/gi, 'человек').replace(/kishi|o'rindiq/gi, 'человек');
  }
  if (lang === 'uz') {
    return str.replace(/\bseats\b|\bpeople\b|\bcapacity\b/gi, 'kishi').replace(/человек|мест/gi, 'kishi');
  }
  return str;
};

export const formatHallPrice = (price, lang) => {
  if (!price) return '';
  const str = String(price);
  if (lang === 'ru') {
    return str.replace(/UZS\s*\/\s*hour/gi, 'сум / час').replace(/so'm\s*\/\s*soat/gi, 'сум / час');
  }
  if (lang === 'uz') {
    return str.replace(/UZS\s*\/\s*hour/gi, "so'm / soat").replace(/сум\s*\/\s*час/gi, "so'm / soat");
  }
  return str;
};

